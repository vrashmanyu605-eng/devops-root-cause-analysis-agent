-- ---------------------------------------------------------------------------
-- raw_logs
-- Every log line ingested from Loki is persisted here before any LLM work.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw_logs (
    id                BIGSERIAL       PRIMARY KEY,
    batch_id          UUID            NOT NULL,
    timestamp         BIGINT          NOT NULL,          -- nanosecond epoch from Loki
    container         VARCHAR(255)    NOT NULL DEFAULT 'unknown',
    host              VARCHAR(255)    NOT NULL DEFAULT 'unknown',
    severity          VARCHAR(20)     NOT NULL DEFAULT 'INFO',   -- CRITICAL|ERROR|WARNING|INFO
    message           TEXT            NOT NULL,
    labels            JSONB,                                      -- all Loki stream labels
    occurrence_count  INTEGER         NOT NULL DEFAULT 1,         -- deduplication count
    created_at        TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_raw_logs_batch_id   ON raw_logs (batch_id);
CREATE INDEX IF NOT EXISTS idx_raw_logs_severity   ON raw_logs (severity);
CREATE INDEX IF NOT EXISTS idx_raw_logs_container  ON raw_logs (container);
CREATE INDEX IF NOT EXISTS idx_raw_logs_timestamp  ON raw_logs (timestamp DESC);

-- ---------------------------------------------------------------------------
-- incidents
-- Extracted by the Incident Extractor agent (Gemini via LiteLLM).
-- Each incident groups one or more related raw_logs into a named failure.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS incidents (
    id                  BIGSERIAL       PRIMARY KEY,
    batch_id            UUID            NOT NULL,
    incident_type       VARCHAR(150),                            -- e.g. DatabaseConnectionFailure
    severity            VARCHAR(20)     NOT NULL DEFAULT 'ERROR',
    container           VARCHAR(255),
    affected_services   TEXT[]          NOT NULL DEFAULT '{}',
    root_cause          TEXT,
    error_pattern       TEXT,
    first_seen          BIGINT,                                  -- nanosecond epoch
    log_count           INTEGER         NOT NULL DEFAULT 1,
    raw_log_ids         BIGINT[]        NOT NULL DEFAULT '{}',   -- FK references into raw_logs
    llm_raw_response    TEXT,                                    -- raw LLM output for debugging
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_incidents_batch_id   ON incidents (batch_id);
CREATE INDEX IF NOT EXISTS idx_incidents_severity   ON incidents (severity);
CREATE INDEX IF NOT EXISTS idx_incidents_container  ON incidents (container);
CREATE INDEX IF NOT EXISTS idx_incidents_created_at ON incidents (created_at DESC);

-- ---------------------------------------------------------------------------
-- mitigations
-- Generated by the Mitigation Generator agent (Gemini via LiteLLM).
-- One mitigation record per incident.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mitigations (
    id                          BIGSERIAL       PRIMARY KEY,
    incident_id                 BIGINT          NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    batch_id                    UUID            NOT NULL,
    priority                    VARCHAR(20)     NOT NULL DEFAULT 'MEDIUM',   -- CRITICAL|HIGH|MEDIUM|LOW
    steps                       JSONB           NOT NULL DEFAULT '[]',        -- ordered action list
    commands                    TEXT[]          NOT NULL DEFAULT '{}',        -- runnable shell commands
    estimated_resolution_time   VARCHAR(100),
    requires_restart            BOOLEAN         NOT NULL DEFAULT FALSE,
    prevention_note             TEXT,
    llm_raw_response            TEXT,
    created_at                  TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mitigations_incident_id ON mitigations (incident_id);
CREATE INDEX IF NOT EXISTS idx_mitigations_batch_id    ON mitigations (batch_id);
CREATE INDEX IF NOT EXISTS idx_mitigations_priority    ON mitigations (priority);

-- ---------------------------------------------------------------------------
-- mitigation_feedback
-- Stores user feedback and operational remarks for past mitigations.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mitigation_feedback (
    id              BIGSERIAL       PRIMARY KEY,
    mitigation_id   BIGINT          NOT NULL UNIQUE REFERENCES mitigations (id) ON DELETE CASCADE,
    feedback        TEXT,
    remarks         TEXT,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mitigation_feedback_mitigation_id ON mitigation_feedback (mitigation_id);

-- ---------------------------------------------------------------------------
-- agent_runs
-- Audit trail for every agent invocation: input/output summaries, timing, errors.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agent_runs (
    id              BIGSERIAL       PRIMARY KEY,
    batch_id        UUID            NOT NULL,
    agent_name      VARCHAR(100)    NOT NULL,   -- orchestrator | incident_extractor | mitigation_generator
    status          VARCHAR(50)     NOT NULL,   -- routing | success | error | skipped
    input_summary   JSONB,
    output_summary  JSONB,
    error_message   TEXT,
    duration_ms     INTEGER,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_agent_runs_batch_id    ON agent_runs (batch_id);
CREATE INDEX IF NOT EXISTS idx_agent_runs_agent_name  ON agent_runs (agent_name);
CREATE INDEX IF NOT EXISTS idx_agent_runs_status      ON agent_runs (status);
CREATE INDEX IF NOT EXISTS idx_agent_runs_created_at  ON agent_runs (created_at DESC);
